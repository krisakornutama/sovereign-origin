const HERE = path.dirname(fileURLToPath(import.meta.url));
export const TASK_NAME = 'Sovereign Agent Runner';
/** ไฟล์ launcher ที่ตัวติดตั้งสร้างเองได้ — ใช้เป็นเป้าของ scheduled task */
export const LAUNCHER_NAME = 'RUN-RUNNER.cmd';

/**
 * หา "รากของชุดติดตั้ง" จากโฟลเดอร์ที่ถูกเรียก
 *
 * ของจริง 25/10/69: ชุด --full วาง setup-machine.mjs ไว้ที่ tools\agent-pack\
 * แต่ join.json/install-plan.json อยู่รากชุด ⇒ หาจาก HERE อย่างเดียวไม่เจอ
 * (ผู้ใช้เห็น "ไม่พบ join.json" ทั้งที่ไฟล์อยู่ครบ)
 * @returns {string} รากชุดที่ใกล้ที่สุด (ไม่เกิน 3 ชั้น) หรือ dir เดิมถ้าไม่เจอ
 */
export function findBundleRoot(dir) {
  let cur = path.resolve(dir || '.');
  for (let i = 0; i < 4; i++) {
    if (fs.existsSync(path.join(cur, 'join.json')) || fs.existsSync(path.join(cur, 'install-plan.json'))) return cur;
    const parent = path.dirname(cur);
    if (parent === cur) break;
    cur = parent;
  }
  return path.resolve(dir || '.');
}

/**
 * โฟลเดอร์ของ runner (ที่มี src/main.mjs) — รองรับทั้งชุดเล็กและชุด --full
 * @returns {string} โฟลเดอร์ที่ควรเขียน .env และตั้ง autostart
 */
export function resolveRunnerDir(dir, bundleRoot = findBundleRoot(dir)) {
  const start = path.resolve(dir || '.');
  if (fs.existsSync(path.join(start, 'src', 'main.mjs'))) return start;
  const full = path.join(bundleRoot, 'sovereign-os', 'agent-runner');
  if (fs.existsSync(path.join(full, 'src', 'main.mjs'))) return full;
  return start;
}

/**
 * สร้าง launcher ที่ทำให้ runner ฟื้นเองหลัง crash/อัปเดต (ถ้ายังไม่มี)
 * เขียนเป็น ASCII ล้วน + CRLF ⇒ batch รันได้ทุก codepage
 * @returns {string} พาธของ launcher ที่ใช้ตั้ง scheduled task ได้
 */
export function ensureLauncher(runnerDir) {
  const file = path.join(runnerDir, LAUNCHER_NAME);
  if (!fs.existsSync(file)) {
    const body = [
      '@echo off',
      'rem Generated by setup-machine.mjs - keeps the machine runner alive',
      'setlocal',
      'cd /d "%~dp0"',
      'title Sovereign Agent Runner',
      ':loop',
      'node src\\main.mjs',
      'set "RC=%ERRORLEVEL%"',
      'if "%RC%"=="86" goto done',
      'if "%RC%"=="0" goto done',
      'echo.',
      'echo [run-runner] runner exited abnormally (exit %RC%) - restarting in 10s',
      'timeout /t 10 /nobreak >nul',
      'goto loop',
      ':done',
      'endlocal & exit /b %RC%',
      '',
    ].join('\r\n');
    fs.writeFileSync(file, body, 'utf8');
  }
  return file;
}

/** โฟลเดอร์ที่อนุญาตให้ HUB จัดการไฟล์ — ค่าเริ่มต้น: โปรไฟล์ผู้ใช้ + ไดรฟ์ที่ติดตั้ง */
export function defaultFsRoots(dir, home = os.homedir()) {
  const roots = [];
  if (home) roots.push(home);
  const drive = path.parse(path.resolve(dir)).root;
  if (drive && !roots.some((r) => r.toLowerCase() === drive.toLowerCase())) roots.push(drive);
  return roots;
}

/** เนื้อหา .env ของเครื่องลูก (CRLF เพราะเป็นไฟล์บน Windows) */
export function buildEnvFile({ hubUrl, token, machineName, executors = 'echo', fsRoots }) {
  const roots = Array.isArray(fsRoots) && fsRoots.length ? fsRoots : defaultFsRoots('.');
  return [
    '# สร้างอัตโนมัติโดย SETUP-MACHINE.cmd — แก้ไขได้ตามต้องการ (ห้าม commit)',
    `HUB_URL=${hubUrl}`,
    `MACHINE_TOKEN=${token}`,
    `MACHINE_NAME=${machineName}`,
    `ENABLED_EXECUTORS=${executors}`,
    '',
    '# ช่องควบคุมระยะไกล (ดูจอ/เมาส์/คีย์บอร์ด/ไฟล์) — สั่งได้เฉพาะ SUPERADMIN ที่ HUB',
    'ENABLE_REMOTE_CONTROL=true',
    'REMOTE_MAX_WIDTH=1280',
    `REMOTE_FS_ROOTS=${roots.join(';')}`,
    '',
    '# จับภาพหน้าจอตอนจบงาน + รอบดึงงาน',
    'CAPTURE_SCREENSHOT=true',
    'POLL_INTERVAL_MS=15000',
    '',
  ].join('\r\n');
}

/**
 * อ่านค่าที่แถมมากับชุดสากร (ไฟล์ enroll-code.txt รูปแบบ KEY=VALUE)
 *   ทำให้ผู้ใช้แค่ดับเบิลคลิก SETUP-MACHINE.cmd ไม่ต้องพิมพ์อะไรเลย
 *   ไฟล์นี้ไม่มี = ต้องพิมพ์ --hub-url/--code เอง (ยังทำได้)
 * @returns {{hubUrl: string, code: string}}
 */
export function readEnrollmentFile(dir) {
  const file = path.join(dir, 'enroll-code.txt');
  const empty = { hubUrl: '', code: '' };
  if (!fs.existsSync(file)) return empty;
  let text = '';
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch {
    return empty;
  }
  const pick = (key) => {
    const m = new RegExp(`^\\s*${key}\\s*=\\s*(.+)$`, 'm').exec(text);
    return m ? m[1].trim() : '';
  };
  return { hubUrl: pick('HUB_URL'), code: pick('MACHINE_ENROLL_CODE') };
}

export function readJoin(dir) {
  const file = path.join(dir, 'join.json');
  if (!fs.existsSync(file)) {
    // ไม่มี join.json = ไม่ใช่ชุดเสีย แต่เป็น "ชุดสากล" ที่ต้องลงทะเบียนเอง
    // (เจ้าของสั่ง 11/10/69: "ไฟล์เดียวจบ ไม่ต้องทำทีละเครื่อง")
    //   → ผู้เรียกต้องตัดสินใจต่อ ไม่ใช่ตายที่นี่
    return {
      ok: false,
      code: 'NO_JOIN',
      error: `ไม่พบ join.json ใน ${dir} — ถ้าเป็นชุดสากล ให้รันด้วย --enroll (ต้องมีรหัสเชิญจากเจ้าของ HUB)`,
    };
  }
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
  } catch (err) {
    return { ok: false, error: `join.json อ่านไม่ได้: ${String(err?.message ?? err)}` };
  }
  const hubUrl = String(parsed?.hubUrl ?? '').trim().replace(/\/$/, '');
  const machineToken = String(parsed?.machineToken ?? '').trim();
  const machineName = String(parsed?.machineName ?? '').trim() || os.hostname();
  if (!/^https?:\/\//.test(hubUrl)) return { ok: false, error: 'join.json ไม่มี hubUrl ที่ถูกต้อง' };
  if (!machineToken) return { ok: false, error: 'join.json ไม่มี machineToken' };
  return { ok: true, hubUrl, machineToken, machineName };
}

function defaultExec(cmd, args) {
  return new Promise((resolve) => {
    execFile(cmd, args, { windowsHide: true, maxBuffer: 1024 * 1024 }, (err, stdout, stderr) => {
      resolve({ code: err ? (typeof err.code === 'number' ? err.code : 1) : 0, stdout: String(stdout ?? ''), stderr: String(stderr ?? '') });
    });
  });
}

function tokenFromEnvText(text) {
  const m = /^\s*MACHINE_TOKEN\s*=\s*(.*)$/m.exec(String(text ?? ''));
  return m ? m[1].trim() : '';
}

/**
 * ใช้แผนติดตั้งกับเครื่องนี้: เขียนโปรไฟล์ + เปิดโมดูลใน .env ของ stack (ถ้ามีอยู่แล้ว)
 * แยกออกมาเพื่อเรียกซ้ำได้จาก setup-first-time.bat หลังสร้าง stack เสร็จ (`--apply-modules`)
 * @returns {{status:'ok'|'warn'|'skipped', detail:string, plan:object|null, profile?:{json:string,text:string}, wroteStackEnv:boolean}}
 */
export function applyInstallPlan(bundleRoot) {
  const read = readInstallPlan(bundleRoot);
  if (!read.ok) {
    return {
      status: read.code === 'no_plan' ? 'skipped' : 'warn',
      detail: read.code === 'no_plan' ? 'ชุดติดตั้งนี้ไม่ได้เลือกฟังก์ชั่นไว้' : read.error,
      plan: null,
      wroteStackEnv: false,
    };
  }
  const plan = read.plan;
  const profile = writeMachineProfile(bundleRoot, plan);
  const parentLabel = plan.parent?.username || 'ยังไม่ระบุเครื่องแม่';
  const enabledLabel = plan.enabledModules.length ? plan.enabledModules.join(',') : 'ทุกโมดูลตามปกติ';
  const stackEnv = path.join(bundleRoot, stackEnvRel());
  if (!fs.existsSync(stackEnv)) {
    return {
      status: 'warn',
      detail: `เครื่องลูกของ "${parentLabel}" · ยังไม่มี ${stackEnvRel()} — รันตัวติดตั้ง stack ก่อน แล้วรันซ้ำเพื่อเปิดโมดูล`,
      plan,
      profile,
      wroteStackEnv: false,
    };
  }
  const before = fs.readFileSync(stackEnv, 'utf8');
  const after = applyPlanToEnvText(before, envLinesForPlan(plan));
  if (after !== before) fs.writeFileSync(stackEnv, after, 'utf8');
  return {
    status: 'ok',
    detail: `เครื่องลูกของ "${parentLabel}" · เปิด ${enabledLabel}`,
    plan,
    profile,
    wroteStackEnv: true,
  };
}

/**
 * ติดตั้งเครื่องนี้เป็นเครื่องลูก
 * @returns {{ ok: boolean, exitCode: number, steps: Array<{name:string,status:string,detail:string}>, report: string, hubUrl: string, machineName: string }}
 */
export async function runSetup({
  dir = HERE,
  fetchImpl = fetch,
  exec = defaultExec,
  platform = process.platform,
  home = os.homedir(),
  machineName = '',
  executors = 'echo',
  force = false,
  skipTask = false,
  log = console.log,
  // ── โหมด "ชุดสากร" (เจ้าของสั่ง 11/10/69: ไฟล์เดียวจบ ไม่ต้องทำทีละเครื่อง) ──
  // ไม่มี join.json = ขอ token ของตัวเองจาก HUB ด้วยรหัสเชิญ แทนที่จะต้องออกชุดใหม่ทีละเครื่อง
  enroll = false,
  hubUrl: hubUrlArg = '',
  enrollCode = process.env.MACHINE_ENROLL_CODE || '',
} = {}) {
  const steps = [];
  const lines = [];
  const add = (name, status, detail = '') => {
    steps.push({ name, status, detail });
    const mark = status === 'ok' ? '✔' : status === 'fail' ? '✘' : status === 'warn' ? '!' : '·';
    const line = `  ${mark} ${name}${detail ? ` — ${detail}` : ''}`;
    lines.push(line);
    log(line);
  };
  const finish = (ok, exitCode, hubUrl = '', name = '') => {
    lines.push('');
    if (ok) lines.push('  ✅ ออนไลน์แล้ว — เปิดหน้าเว็บ HUB → คิวเอเจนต์ จะเห็นเครื่องนี้');
    return { ok, exitCode, steps, report: lines.join('\n'), hubUrl, machineName: name };
  };

  lines.push('══════════════════════════════════════════════════');
  lines.push('  Sovereign OS — ติดตั้งเครื่องนี้เป็นเครื่องลูก');
  lines.push('══════════════════════════════════════════════════');

  // 1) ชุดติดตั้งครบไหม
  //    ชุด --full เรียกจาก tools\agent-pack แต่ไฟล์ข้อมูลอยู่รากชุด ⇒ หารากก่อน
  const bundleRoot = findBundleRoot(dir);
  const runnerDir = resolveRunnerDir(dir, bundleRoot);
  const join = readJoin(bundleRoot);

  // โหมดชุดสากร: ไม่มี join.json แต่มี --enroll ⇒ ขอ token เอง
  let resolved = join.ok ? { hubUrl: join.hubUrl, machineToken: join.machineToken, machineName: join.machineName } : null;
  if (!resolved && enroll && join.code === 'NO_JOIN') {
    // pathToFileURL จำเป็น: บน Windows `await import('E:\\...')` โยน ERR_UNSUPPORTED_ESM_URL_SCHEME
//   (เคสจริง 11/10/69 — ทดสอบชุดสากรจริงแล้วพังตรงนี้ ยังไม่ได้ไปถึงเครื่องปลายทาง)
const { enroll: doEnroll } = await import(pathToFileURL(path.join(dir, 'src', 'enroll-machine.mjs')).href);
    // ลำดับค่ามา: สิ่งที่สั่งเอง > ตัวแปรแวดล้อม > ไฟล์ที่แถมมากับชุดสากร
    const preset = readEnrollmentFile(dir);
    const hub = String(hubUrlArg || process.env.HUB_URL || preset.hubUrl || '').trim();
    const code = String(enrollCode || process.env.MACHINE_ENROLL_CODE || preset.code || '').trim();
    const r = await doEnroll(
      { hubUrl: hub, code, name: machineName || os.hostname(), os: platform, executors: String(executors).split(',').map((s) => s.trim()).filter(Boolean), version: '' },
      { fetch: fetchImpl },
    );
    if (!r.ok) {
      add('ลงทะเบียน', 'fail', r.error);
      return finish(false, 1);
    }
    resolved = { hubUrl: hub.replace(/\/+$/, ''), machineToken: r.token, machineName: r.name || machineName || os.hostname() };
    add('ลงทะเบียน', 'ok', `ขอ token สำเร็จ — เครื่อง "${resolved.machineName}"`);
  }

  if (!resolved) {
    add('join', 'fail', join.error);
    return finish(false, 1);
  }
  const name = String(machineName || resolved.machineName || os.hostname()).trim() || resolved.machineName;
  add('join', 'ok', `เครื่อง "${name}" → HUB ${resolved.hubUrl}`);

  // 2) ต่อ HUB ได้ไหม (ก่อนแตะไฟล์)
  let health;
  try {
    const res = await fetchImpl(`${resolved.hubUrl}/api/health`, { method: 'GET' });
    health = { status: res?.status ?? 0, ok: Boolean(res?.ok || (res?.status ?? 0) < 400) };
  } catch (err) {
    health = { status: 0, ok: false, error: String(err?.message ?? err) };
  }
  if (!health.ok) {
    add('hub', 'fail', `ต่อ ${resolved.hubUrl}/api/health ไม่ได้ (${health.error || health.status})`);
    lines.push('  ตรวจ: HUB เปิดอยู่ไหม · เปิด firewall พอร์ต 3000 (profile private) · Wi-Fi วงเดียวกันไหม');
    lines.push(`  ทดสอบเองได้: curl -L ${resolved.hubUrl}/api/health`);
    return finish(false, 1, resolved.hubUrl, name);
  }
  add('hub', 'ok', `HUB ตอบ ${health.status} ที่ ${resolved.hubUrl}`);

  // 3) .env (ไม่ทับของเดิมที่ไม่ใช่ token ชุดนี้) — เขียนที่โฟลเดอร์ runner เท่านั้น
  const envPath = path.join(runnerDir, '.env');
  const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : null;
  const fsRoots = defaultFsRoots(runnerDir, home);
  let wroteEnv = false;
  if (existing) {
    const existingToken = tokenFromEnvText(existing);
    if (existingToken === resolved.machineToken) {
      add('env', 'ok', 'มี .env ของเครื่องนี้อยู่แล้ว (ไม่แก้)');
    } else if (!force) {
      add('env', 'fail', 'มี .env อยู่แล้วแต่ token ไม่ตรงกับชุดติดตั้งนี้');
      lines.push('  ถ้าตั้งใจให้เครื่องนี้ใช้ token ใหม่: รันซ้ำด้วย --force (จะสำรอง .env เดิมเป็น .env.bak)');
      lines.push('  ถ้าไม่ตั้งใจ: ตรวจว่าคุณกำลังติดตั้งทับเครื่องที่ใช้งานอยู่หรือไม่');
      return finish(false, 1, resolved.hubUrl, name);
    } else {
      fs.writeFileSync(`${envPath}.bak`, existing, 'utf8');
      fs.writeFileSync(envPath, buildEnvFile({ hubUrl: resolved.hubUrl, token: resolved.machineToken, machineName: name, executors, fsRoots }), 'utf8');
      wroteEnv = true;
      add('env', 'warn', 'เขียน .env ใหม่ (สำรองของเดิมเป็น .env.bak)');
    }
  } else {
    fs.writeFileSync(envPath, buildEnvFile({ hubUrl: resolved.hubUrl, token: resolved.machineToken, machineName: name, executors, fsRoots }), 'utf8');
    wroteEnv = true;
    add('env', 'ok', `เขียน .env แล้ว (ขอบเขตไฟล์: ${fsRoots.join(' | ')})`);
  }

  // 4) พิสูจน์ว่า token ใช้ได้จริง = เครื่องออนไลน์
  let hb;
  try {
    const res = await fetchImpl(`${resolved.hubUrl}/api/agent-machines/heartbeat`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-machine-token': resolved.machineToken },
      body: JSON.stringify({ version: process.version }),
    });
    hb = { status: res?.status ?? 0 };
  } catch (err) {
    hb = { status: 0, error: String(err?.message ?? err) };
  }
  if (hb.status !== 200) {
    add('heartbeat', 'fail', `HUB ตอบ ${hb.status || hb.error} — ยังไม่ถือว่าออนไลน์`);
    lines.push(
      hb.status === 401
        ? '  token ถูกปฏิเสธ (401): เครื่องนี้อาจถูกลบ/ปิดในหน้า HUB หรือ join.json ถูกแก้ — แพ็กชุดติดตั้งใหม่ที่เครื่อง HUB'
        : '  ตรวจว่า route /api/agent-machines ทำงาน (deploy ล่าสุด) แล้วลองใหม่'
    );
    return finish(false, 1, resolved.hubUrl, name);
  }
  add('heartbeat', 'ok', 'HUB ยอมรับ token นี้ — เครื่องขึ้นออนไลน์แล้ว');

  // 4.5) แผนติดตั้ง: เครื่องนี้เป็นลูกของใคร + เปิดฟังก์ชั่นที่เลือกไว้จริง
  //      (เขียนหลัง heartbeat ผ่าน — token พิสูจน์แล้วว่าเป็นเครื่องจริงก่อนแตะ config ของ stack)
  let plan = null;
  const applied = applyInstallPlan(bundleRoot);
  plan = applied.plan;
  if (!plan) {
    add('modules', applied.status, applied.detail);
  } else {
    try {
      lines.push('');
      lines.push(`  เครื่องแม่ : ${plan.parent?.username || 'ยังไม่ระบุเครื่องแม่'}`);
      lines.push(`  ฟังก์ชั่น  : ${summarizeModules(plan.modules)}`);
      if (applied.profile) lines.push(`  โปรไฟล์   : ${applied.profile.text}`);
      add('modules', applied.status, applied.detail);
      if (!applied.wroteStackEnv) {
        lines.push('  (ตัวรันงานพร้อมใช้แล้ว — ฟังก์ชั่นบนหน้าเว็บจะเปิดเมื่อ stack ของเครื่องนี้ถูกติดตั้ง)');
      }
    } catch (err) {
      add('modules', 'warn', `อ่านแผนแล้วแต่เขียนโปรไฟล์ไม่สำเร็จ: ${String(err?.message ?? err)}`);
    }
  }

  // 5) autostart (Windows) — ไม่ผ่านก็ยังใช้ได้ แค่ต้องรันเอง
  if (skipTask) {
    add('task', 'skipped', 'ข้ามตามที่สั่ง (--no-task)');
  } else if (platform !== 'win32') {
    add('task', 'warn', `ไม่ใช่ Windows — รันเองได้: cd ${runnerDir} && node src/main.mjs`);
  } else {
    // ตัวห่อทำสองอย่าง: (ก) process ตายแล้วเริ่มใหม่ให้เอง (เครื่องไม่หลุดจาก HUB)
    // (ข) รับช่วงตอน runner อัปเดตโค้ดตัวเอง (exit 86) โดยไม่สร้างตัวซ้อน
    // ใช้ launcher ที่อยู่ในโฟลเดอร์ runner จริง (ชุด --full อยู่ sovereign-os/agent-runner)
    const launcher = ensureLauncher(runnerDir);
    const hasWrapper = fs.existsSync(launcher);
    const tr = hasWrapper ? `cmd /c "${launcher}"` : `cmd /c cd /d "${runnerDir}" && node src\\main.mjs`;
    const res = await exec('schtasks', ['/Create', '/TN', TASK_NAME, '/TR', tr, '/SC', 'ONLOGON', '/F']);
    if (res?.code === 0) {
      add(
        'task',
        'ok',
        hasWrapper
          ? `ตั้งให้รันเองตอนล็อกอินแล้ว (${TASK_NAME}) — ผ่าน ${LAUNCHER_NAME} (ตายแล้วฟื้นเอง)`
          : `ตั้งให้รันเองตอนล็อกอินแล้ว (${TASK_NAME})`,
      );
      if (!hasWrapper) lines.push(`  ! สร้าง ${LAUNCHER_NAME} ไม่สำเร็จ — ตัว runner จะยังรีสตาร์ทตัวเองหลังอัปเดตได้ แต่จะไม่ฟื้นเองเมื่อ crash`);
    } else {
      add('task', 'warn', 'ตั้ง autostart ไม่สำเร็จ (ต้องสิทธิ์ผู้ดูแลระบบ)');
      lines.push('  วิธีตั้ง autostart: คลิกขวา SETUP-MACHINE.cmd → "Run as administrator" แล้วรันอีกครั้ง');
      lines.push(`  ระหว่างนี้รันเองได้: cd /d ${runnerDir} && node src\\main.mjs`);
    }
  }

  if (wroteEnv) lines.push('');
  lines.push(`  HUB_URL : ${resolved.hubUrl}`);
  lines.push(`  ชื่อเครื่อง: ${name}`);
  lines.push(`  โฟลเดอร์ : ${runnerDir}`);
  if (plan?.parent?.username) lines.push(`  เครื่องแม่ : ${plan.parent.username} — ควบคุมเครื่องนี้ได้ทันที`);
  return finish(true, 0, resolved.hubUrl, name);
}

