export function compareMbti(a: MbtiResult, b: MbtiResult): { dims: CompareDimRow[]; summary: CompareSummary } {
  const dims: CompareDimRow[] = (['EI', 'SN', 'TF', 'JP'] as MbtiDim[]).map((dim) => {
    const da = a.dims.find((d) => d.dim === dim);
    const db = b.dims.find((d) => d.dim === dim);
    const aLetter = da?.letter ?? '?';
    const bLetter = db?.letter ?? '?';
    let relation: CompareDimRow['relation'];
    if (aLetter === bLetter) relation = 'same';
    else {
      // ตัวอักษรต่างกัน — ดูว่าผลชัดพอไหมทั้งสองฝั่ง (clarity >= 30 = ชัด)
      const bothClear = (da?.clarity ?? 0) >= 30 && (db?.clarity ?? 0) >= 30;
      if (!bothClear) relation = 'adjacent'; // ฝั่งใดฝั่งหนึ่งก้ำกึ่ง → ต่างกันเพียงเล็กน้อย
      else if (dim === 'TF' || dim === 'JP') relation = 'clash'; // ตรงข้ามชัดในมิติที่มีแรงเสียดสี
      else relation = 'mirror'; // ตรงข้ามชัดใน EI/SN → สมดุลเชิงเสริมกัน
    }
    const note = PAIR_NOTES[relation][dim];
    return { dim, label: DIM_LABELS[dim], aLetter, bLetter, relation, note };
  });
  const sameCount = dims.filter((d) => d.relation === 'same').length;
  const diffCount = 4 - sameCount;
  const headline = sameCount >= 3
    ? 'รากฐานเหมือนกันมาก — เข้าใจกันเร็ว เดินบ้านได้ลื่น แต่ต้องตั้งใจหา "แลนส์ต่างมุม" จากภายนอกบ้าง'
    : sameCount === 2
      ? 'คู่สมดุลแบบคลาสสิก — เหมือนกันครึ่งทาง ต่างกันครึ่งทาง โอกาสเติบโตซ่อนอยู่ในมิติที่ต่างกัน'
      : 'คู่ต่างขั้ว — สนุกและเรียนรู้จากกันมากที่สุด แต่ต้องอาศัย "การแปลภาษา" เป็นวิถีปกติ ไม่ใช่การประนีประนอมตอนพัง';
  return { dims, summary: { headline, sameCount, diffCount } };
}
