export function careToneFor(code: string | null | undefined): CareTone | null {
  if (!code) return null;
  const t = CARE_TONES[code];
  return t ? { ...t, code } : null;
}

/** ผลล่าสุดจาก localStorage (ฝั่ง client เท่านั้น) */
export function latestLocalResult(): MbtiResult | null {
  if (typeof window === 'undefined') return null;
  try {
    const arr = JSON.parse(localStorage.getItem(MBTI_STORE_KEY) || '[]');
    return Array.isArray(arr) && arr.length > 0 ? (arr[0] as MbtiResult) : null;
  } catch { return null; }
}

