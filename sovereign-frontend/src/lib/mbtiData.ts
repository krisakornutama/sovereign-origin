export interface DimScore {
  dim: MbtiDim;
  first: string; second: string; // เช่น 'E', 'I'
  firstCount: number; secondCount: number;
  firstPct: number; // % ฝั่งแรก (E/S/T/J)
  clarity: number; // ความชัด 0–100
  letter: string; // ตัวอักษรที่ชนะ (tie → ตัวแรก)
}

export interface MbtiResult {
  code: string;
  dims: DimScore[];
  answered: number;
  date: string;
}

/** คำนวณจากคำตอบ: { [id]: 0 (ตัวเลือก A) | 1 (ตัวเลือก B) } */
export function scoreMbti(answers: Record<number, number>): MbtiResult {
  const cfg: Array<{ dim: MbtiDim; first: string; second: string; total: number }> = [
    { dim: 'EI', first: 'E', second: 'I', total: 21 },
    { dim: 'SN', first: 'S', second: 'N', total: 26 },
    { dim: 'TF', first: 'T', second: 'F', total: 28 },
    { dim: 'JP', first: 'J', second: 'P', total: 18 },
  ];
  const dims = cfg.map(({ dim, first, second }) => {
    const qs = MBTI_QUESTIONS.filter((q) => q.d === dim);
    let firstCount = 0;
    for (const q of qs) {
      const ans = answers[q.id];
      if (ans === undefined) continue;
      if (ans === 0) firstCount += 1;
    }
    const answered = qs.filter((q) => answers[q.id] !== undefined).length;
    const secondCount = answered - firstCount;
    const denom = Math.max(1, answered);
    const firstPct = Math.round((firstCount / denom) * 100);
    const letter = firstCount >= secondCount ? first : second; // เสมอกัน → ตัวแรก (ฝั่ง E/S/T/J)
    return { dim, first, second, firstCount, secondCount, firstPct, clarity: Math.abs(firstPct * 2 - 100), letter };
  });
  return { code: dims.map((d) => d.letter).join(''), dims, answered: Object.keys(answers).length, date: new Date().toISOString() };
}

export function typeInfo(code: string): MbtiTypeInfo | undefined {
  return MBTI_TYPES.find((t) => t.code === code);
}

