// ── ผลข้างเคียงที่ตั้งใจ: ตอน SSR/ก่อน hydrate isAuthenticated=false เสมอ → เมนูไม่อยู่ใน HTML ที่ส่งให้บอท
// หน้าในระบบทุกหน้าคืน "กำลังโหลด…" ตอน !isHydrated อยู่แล้ว จึงไม่มีแฟลชของเมนูบนหน้าเจ้าของ
'use client';
import { useAuthStore } from '../stores/useAuthStore';

/** true = ต้องซ่อน Sidebar / แถบเมนูมือถือ / Command Palette ทิ้ง */
export function useHideInternalNav(): boolean {
  return !useAuthStore((s) => s.isAuthenticated);
}